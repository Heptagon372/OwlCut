export const MESSAGES = { ko, en } as const;

/** {name} 자리에 값을 넣는다. 없는 키는 한국어 → 키 자체로 대체해 화면이 비지 않게. */
export function translate(
  lang: "ko" | "en",
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  const table = MESSAGES[lang] as Record<MessageKey, string>;
  const raw = table[key] ?? (ko as Record<MessageKey, string>)[key] ?? key;
  if (!vars) return raw;
  return raw.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}
